static int rb_wlan_data_unpack_erd(const u16 tag_id, const u8 *inbuf, size_t inlen,
				   void *outbuf, size_t *outlen)
{
	u16 lzo_ofs, lzo_len;
	int ret;

	/* Find embedded tag */
	ret = rb_tag_find(inbuf, inlen, tag_id, &lzo_ofs, &lzo_len);
	if (ret) {
		pr_debug("[rb_wlan] " "no ERD data for id 0x%04x\n", tag_id);
		goto fail;
	}

	if (lzo_len > inlen) {
		pr_debug("[rb_wlan] " "Invalid ERD data length\n");
		ret = -EINVAL;
		goto fail;
	}

	ret = lzo1x_decompress_safe(inbuf+lzo_ofs, lzo_len, outbuf, outlen);
	if (ret)
		pr_debug("[rb_wlan] " "LZO decompression error (%d)\n", ret);

fail:
	return ret;
}

/*
 * If the RB_ID_WLAN_DATA payload starts with RB_MAGIC_LZOR, then past
 * that magic number is a payload that must be appended to the rb_lzor_prefix,
 * the resulting blob is LZO-compressed.
 * If payload starts with RB_MAGIC_LZ77, a separate (bit level LZ77)
 * decompression function needs to be used. In the decompressed result,
 * the RB_MAGIC_ERD magic number (aligned) must be located. Following that
 * magic, there is one or more routerboot tag node(s) locating the RLE-encoded
 * calibration data payload.
 */
static int rb_wlan_data_unpack_lzor_lz77(const u16 tag_id, const u8 *inbuf, size_t inlen,
					 void *outbuf, size_t *outlen, u32 magic)
{
	u16 rle_ofs, rle_len;
	const u32 *needle;
	u8 *tempbuf;
	size_t templen, lzo_len;
	int ret;
	const char lzor[] = "LZOR";
	const char lz77[] = "LZ77";
	const char *lz_type;

	/* Temporary buffer same size as the outbuf */
	templen = *outlen;
	tempbuf = kmalloc(templen, GFP_KERNEL);
	if (!tempbuf)
		return -ENOMEM;

	lzo_len = inlen;
	if (magic == RB_MAGIC_LZOR)
		lzo_len += sizeof(rb_lzor_prefix);
	if (lzo_len > *outlen) {
		ret = -EFBIG;
		goto fail;
	}

	switch (magic) {
	case RB_MAGIC_LZOR:
		lz_type = lzor;

		/* Concatenate into the outbuf */
		memcpy(outbuf, rb_lzor_prefix, sizeof(rb_lzor_prefix));
		memcpy(outbuf + sizeof(rb_lzor_prefix), inbuf, inlen);

		/* LZO-decompress lzo_len bytes of outbuf into the tempbuf */
		ret = lzo1x_decompress_safe(outbuf, lzo_len, tempbuf, &templen);
		if (ret) {
			if (LZO_E_INPUT_NOT_CONSUMED == ret) {
				/*
				 * The tag length is always aligned thus the LZO payload may be padded,
				 * which can trigger a spurious error which we ignore here.
				 */
				pr_debug("[rb_wlan] " "LZOR: LZO EOF before buffer end - this may be harmless\n");
			} else {
				pr_debug("[rb_wlan] " "LZOR: LZO decompression error (%d)\n", ret);
				goto fail;
			}
		}
		break;
	case RB_MAGIC_LZ77:
		lz_type = lz77;
		/* LZO-decompress lzo_len bytes of inbuf into the tempbuf */
		ret = rb_lz77_decompress(inbuf, inlen, tempbuf, &templen);
		if (ret) {
			pr_err("[rb_wlan] " "LZ77: LZ77 decompress error %d\n", ret);
			goto fail;
		}

		pr_debug("[rb_wlan] " "LZ77: decompressed from %zu to %zu\n",
				inlen, templen);
		break;
	default:
		ret = -EINVAL;
		goto fail;
	}

	/*
	 * Post decompression we have a blob (possibly byproduct of the lzo
	 * dictionary). We need to find RB_MAGIC_ERD. The magic number seems to
	 * be 32bit-aligned in the decompression output.
	 */
	needle = (const u32 *)tempbuf;
	while (RB_MAGIC_ERD != *needle++) {
		if ((u8 *)needle >= tempbuf+templen) {
			pr_warn("[rb_wlan] " "%s: ERD magic not found. Decompressed first word: 0x%08x\n", lz_type, *(u32 *)tempbuf);
			ret = -ENODATA;
			goto fail;
		}
	}
	templen -= (u8 *)needle - tempbuf;

	/* Past magic. Look for tag node */
	ret = rb_tag_find((u8 *)needle, templen, tag_id, &rle_ofs, &rle_len);
	if (ret) {
		pr_debug("[rb_wlan] " "%s: no RLE data for id 0x%04x\n", lz_type, tag_id);
		goto fail;
	}

	if (rle_len > templen) {
		pr_debug("[rb_wlan] " "%s: Invalid RLE data length\n", lz_type);
		ret = -EINVAL;
		goto fail;
	}

	/* RLE-decode tempbuf from needle back into the outbuf */
	ret = rb_rle_decode((u8 *)needle+rle_ofs, rle_len, outbuf, outlen);
	if (ret)
		pr_debug("[rb_wlan] " "%s: RLE decoding error (%d)\n", lz_type, ret);

fail:
	kfree(tempbuf);
	return ret;
}

int rb_wlan_data_unpack(const u8 *inbuf, size_t tlen, const u16 tag_id,
			void *outbuf, size_t *outlen)
{
	const u8 *lbuf;
	u32 magic;
	int ret;

	if (tlen < sizeof(magic))
		return -EINVAL;

	lbuf = inbuf;
	magic = *(u32 *)lbuf;

	ret = -ENODATA;
	switch (magic) {
	case RB_MAGIC_LZ77:
		/* no known instances of lz77 without 8001/8201 data, skip SOLO */
		if (tag_id == RB_WLAN_ERD_ID_SOLO) {
			pr_debug("[rb_wlan] " "skipped LZ77 decompress in search for SOLO tag\n");
			break;
		}
		fallthrough;
	case RB_MAGIC_LZOR:
		/* Skip magic */
		lbuf += sizeof(magic);
		tlen -= sizeof(magic);
		ret = rb_wlan_data_unpack_lzor_lz77(tag_id, lbuf, tlen, outbuf, outlen, magic);
		break;
	case RB_MAGIC_ERD:
		/* Skip magic */
		lbuf += sizeof(magic);
		tlen -= sizeof(magic);
		ret = rb_wlan_data_unpack_erd(tag_id, lbuf, tlen, outbuf, outlen);
		break;
	default:
		/*
		 * If the RB_ID_WLAN_DATA payload doesn't start with a
		 * magic number, the payload itself is the raw RLE-encoded
		 * calibration data. Only RB_WLAN_ERD_ID_SOLO makes sense here.
		 */
		if (RB_WLAN_ERD_ID_SOLO == tag_id) {
			ret = rb_rle_decode(lbuf, tlen, outbuf, outlen);
			if (ret)
				pr_debug("[rb_wlan] " "RLE decoding error (%d)\n", ret);
		}
		break;
	}

	return ret;
}
EXPORT_SYMBOL_GPL(rb_wlan_data_unpack);
