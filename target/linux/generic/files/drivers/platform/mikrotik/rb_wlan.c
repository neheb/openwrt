static int rb_tag_find(const u8 *bufhead, const size_t buflen, const u16 tag_id,
			       u16 *pld_ofs, u16 *pld_len)
{
	const u32 *datum, *bufend;
	u32 node;
	u16 id, len;

	if (!bufhead || !tag_id)
		return -EINVAL;

	datum = (const u32 *)bufhead;
	bufend = (const u32 *)(bufhead + buflen);

	while (datum < bufend) {
		node = *datum++;
		if (!node)
			break;

		id = node & 0xffff;
		len = node >> 16;

		if (tag_id == id) {
			if (datum >= bufend)
				break;

			if (pld_ofs)
				*pld_ofs = (u16)((u8 *)datum - bufhead);
			if (pld_len)
				*pld_len = len;

			return 0;
		}

		len = ALIGN(len, sizeof(*datum));
		datum += len / sizeof(*datum);
	}

	return -ENOENT;
}

static int rb_rle_decode(const u8 *in, size_t inlen, u8 *out, size_t *outlen)
{
	int ret, run, nbytes;
	u8 byte;

	if (!in || (inlen < 2) || !out)
		return -EINVAL;

	ret = -ENOSPC;
	nbytes = 0;
	while (inlen >= 2) {
		run = *in++;
		inlen--;

		if (run & 0x80) {
			run = ~run & 0xff;
			run++;

			if (run > inlen)
				goto fail;

			inlen -= run;
			nbytes += run;
			if (nbytes > *outlen)
				goto fail;

			while (run-- > 0)
				*out++ = *in++;
		} else {
			byte = *in++;
			inlen--;

			nbytes += run;
			if (nbytes > *outlen)
				goto fail;

			while (run-- > 0)
				*out++ = byte;
		}
	}

	ret = 0;
fail:
	*outlen = nbytes;
	return ret;
}

